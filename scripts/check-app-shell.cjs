'use strict';
const fs=require('fs');
const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const output='docs/verification/app-shell';
const results=[];
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000},locale:'ja-JP',serviceWorkers:'block'});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    for(const route of ['/','/report','/profile','/food','/admin']) {
      const before=errors.length;
      const response=await page.goto('http://localhost:8410'+route);
      assert.equal(response.status(),200);
      await page.waitForTimeout(8000);
      assert.equal(await page.locator('main#app-main').count(),1);
      assert.equal(await page.locator('header#toolbar').count(),1);
      assert.equal(await page.locator('#app-nav [aria-current="page"]').getAttribute('href'),route);
      assert(await page.locator('h1').isVisible());
      assert.deepEqual(errors.slice(before),[]);
      results.push({case:'desktop route '+route+' renders shared shell without page errors',pass:true});
    }
    await page.goto('http://localhost:8410/');
    await page.waitForFunction(()=>!document.querySelector('#container').classList.contains('loading'));
    await page.waitForTimeout(2000);
    await page.locator('.focus-range li[data-hours="6"] button').click();
    assert.equal(await page.evaluate(()=>window.Nightscout.client.focusRangeMS),21600000);
    assert.equal(await page.locator('.focus-range li[data-hours="6"] button').getAttribute('aria-pressed'),'true');
    await page.locator('.focus-range li[data-hours="3"] button').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(()=>window.Nightscout.client.focusRangeMS),10800000);
    const selectedBackground=await page.locator('.focus-range li.selected button').evaluate(el=>getComputedStyle(el).backgroundColor);
    const unselectedBackground=await page.locator('.focus-range li[data-hours="6"] button').evaluate(el=>getComputedStyle(el).backgroundColor);
    assert.notEqual(selectedBackground,unselectedBackground);
    await page.locator('.focus-range li:not([data-hours]) button').click();
    assert(await page.locator('#viewMenu').isVisible());
    await page.keyboard.press('Escape');await page.locator('h1').click();
    await page.locator('#drawerToggle').click();
    await page.waitForTimeout(400);
    assert(await page.locator('#settings-form').isVisible());
    await page.locator('#drawer [data-drawer-close]').click();await page.waitForTimeout(400);
    const chart=await page.locator('#chartContainer').boundingBox();
    assert(chart.x>=240&&chart.width>0&&chart.height>0);
    await page.screenshot({path:output+'/desktop.png'});
    results.push({case:'native range buttons retain 6-hour click and 3-hour keyboard selection; options and settings open',chart,pass:true});
    await page.keyboard.press('Control+Home');
    await page.locator('.app-skip-link').focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator(':focus').getAttribute('id'),'app-main');
    results.push({case:'skip link moves keyboard focus to main',pass:true});
    await page.setViewportSize({width:390,height:844});
    await page.waitForTimeout(500);
    const ranges=await page.locator('.focus-range').boundingBox();
    const status=await page.locator('.status').boundingBox();
    const mobileChart=await page.locator('#chartContainer').boundingBox();
    assert(ranges.y>=status.y+status.height);
    assert(mobileChart.y>=ranges.y+ranges.height);
    assert(mobileChart.height>=384);
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    results.push({case:'mobile controls stay below cards; chart has readable height without horizontal page overflow',ranges,mobileChart,pass:true});
    await page.locator('#app-nav-toggle').click();
    assert.equal(await page.locator('#app-nav').getAttribute('role'),'dialog');
    assert.equal(await page.locator('#app-nav').getAttribute('aria-modal'),'true');
    assert(await page.locator('#app-main').evaluate(el=>el.inert));
    assert.equal(await page.locator(':focus').getAttribute('id'),'app-nav-close');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.locator(':focus').getAttribute('href'),'/split');
    await page.keyboard.press('Tab');assert.equal(await page.locator(':focus').getAttribute('id'),'app-nav-close');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#app-nav-toggle').getAttribute('aria-expanded'),'false');
    assert.equal(await page.locator(':focus').getAttribute('id'),'app-nav-toggle');
    assert(!(await page.locator('#app-main').evaluate(el=>el.inert)));
    await page.locator('#app-nav-toggle').click();
    await page.locator('#app-nav-backdrop').click({position:{x:380,y:400}});
    assert.equal(await page.locator('#app-nav-toggle').getAttribute('aria-expanded'),'false');
    await page.screenshot({path:output+'/mobile.png',fullPage:true});
    results.push({case:'mobile drawer traps Tab, closes by Escape and backdrop, returns focus and releases main',pass:true});
    await page.setViewportSize({width:1440,height:1000});
    assert(await page.locator('#app-nav').isVisible());assert(!(await page.locator('#app-nav-toggle').isVisible()));
    results.push({case:'desktop resize restores navigation',pass:true});
    fs.writeFileSync(output+'/results.json',JSON.stringify({results,pageErrors:errors},null,2));
    console.log(JSON.stringify(results,null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
